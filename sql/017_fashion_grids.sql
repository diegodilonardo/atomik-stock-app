IF OBJECT_ID('dbo.FASHION_GRIDS','U') IS NULL
BEGIN
  CREATE TABLE dbo.FASHION_GRIDS (
    ID_GRID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    ID_EMPRESA INT NOT NULL REFERENCES dbo.EMPRESAS(ID_EMPRESA),
    NAME NVARCHAR(150) NOT NULL,
    SELECTION_JSON NVARCHAR(MAX) NOT NULL CHECK(ISJSON(SELECTION_JSON)=1),
    VERSION INT NOT NULL DEFAULT 1,
    ACTIVE BIT NOT NULL DEFAULT 1,
    UPDATED_BY INT NOT NULL REFERENCES dbo.USERS(ID_USER),
    UPDATED_AT DATETIME2(0) NOT NULL DEFAULT SYSDATETIME()
  );
  CREATE UNIQUE INDEX UX_FASHION_GRID_NAME ON dbo.FASHION_GRIDS(ID_EMPRESA,NAME) WHERE ACTIVE=1;
END;
